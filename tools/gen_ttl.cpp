namespace {

constexpr const char* kUri =
    "https://github.com/tylorismusic-commits/patina";
constexpr const char* kName = "Patina";
constexpr const char* kShortDesc = "Five-model saturation and multiband colour";
constexpr const char* kDescription =
    "Valve, Console, Bus, Tape and Transformer saturation, single-band or "
    "2/3/4-band multiband with per-band Level, draggable Linkwitz-Riley "
    "crossovers and an FFT spectrum.";
constexpr const char* kLicense = "https://spdx.org/licenses/GPL-3.0-or-later.html";
constexpr const char* kMaintainer = "tylorismusic";
constexpr const char* kHomepage =
    "https://github.com/tylorismusic-commits/patina";
constexpr const char* kPluginBinary = "patina.so";
constexpr const char* kUiBinary = "patina_ui.so";

std::string groupSlug(const char* module) {
  std::string out;
  for (const char* p = module; *p; ++p) {
    if (*p != ' ' && *p != '\t') {
      out += static_cast<char>(std::tolower(static_cast<unsigned char>(*p)));
    }
  }
  return out;
}

std::string groupUri(const char* module) {
  return std::string(kUri) + "#" + groupSlug(module);
}

std::string groupSymbol(const char* module) {
  std::string out;
  for (const char* p = module; *p; ++p) {
    const unsigned char c = static_cast<unsigned char>(*p);
    if (std::isalnum(c)) {
      out += static_cast<char>(std::tolower(c));
    } else if (!out.empty() && out.back() != '_') {
      out += '_';
    }
  }
  while (!out.empty() && out.back() == '_') {
    out.pop_back();
  }
  return out.empty() ? "group" : out;
}

std::string num(double v) {
  char buf[64];
  std::snprintf(buf, sizeof(buf), "%.6g", v);
  return buf;
}

std::string escaped(const std::string& s) {
  std::string out;
  for (char c : s) {
    if (c == '"' || c == '\\') {
      out += '\\';
    }
    out += c;
  }
  return out;
}

// Lowercase, alphanumerics only, single dashes between words.
std::string slug(const std::string& s) {
  std::string out;
  for (char c : s) {
    if (std::isalnum(static_cast<unsigned char>(c))) {
      out += static_cast<char>(std::tolower(static_cast<unsigned char>(c)));
    } else if (!out.empty() && out.back() != '-') {
      out += '-';
    }
  }
  while (!out.empty() && out.back() == '-') {
    out.pop_back();
  }
  return out.empty() ? "group" : out;
}

bool isToggle(const patina::ParamSpec& s) {
  return s.stepped && s.min == 0.0 && s.max == 1.0;
}

const char* paramUnit(const patina::ParamSpec& s) {
  if (std::strstr(s.symbol, "xover") != nullptr) {
    return "hz";
  }
  return nullptr;
}

std::string portBlock(int index, const char* symbol, const char* name,
                      double minimum, double maximum, double def, bool integer,
                      bool toggled, const patina::Labels& labels,
                      const char* unit, const char* group, bool output,
                      bool hidden) {
  std::ostringstream out;
  out << "    [\n";
  out << "        a lv2:" << (output ? "OutputPort" : "InputPort")
      << " , lv2:ControlPort ;\n";
  out << "        lv2:index " << index << " ;\n";
  out << "        lv2:symbol \"" << symbol << "\" ;\n";
  out << "        lv2:name \"" << name << "\" ;\n";
  out << "        lv2:default " << num(def) << " ;\n";
  out << "        lv2:minimum " << num(minimum) << " ;\n";
  out << "        lv2:maximum " << num(maximum) << " ;\n";
  if (integer) {
    out << "        lv2:integer true ;\n";
  }
  if (toggled) {
    out << "        lv2:toggled true ;\n";
  }
  if (labels.count > 0) {
    out << "        lv2:scalePoint ";
    for (int i = 0; i < labels.count; ++i) {
      if (i > 0) {
        out << " ,\n            ";
      }
      out << "[ rdf:value " << num(integer ? minimum + i : i)
          << " ; rdfs:label \"" << escaped(labels.names[i]) << "\" ]";
    }
    out << " ;\n";
  }
  if (unit) {
    out << "        units:unit units:" << unit << " ;\n";
  }
  if (output || hidden) {
    out << "        lv2:portProperty pprops:notOnGUI ;\n";
  }
  out << "        pg:group <" << group << "> ;\n";
  out << "    ]";
  return out.str();
}

std::string buildPluginTtl() {
  std::ostringstream out;
  out << "# Generated by tools/gen_ttl.cpp - do not edit.\n";
  out << "@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n";
  out << "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n";
  out << "@prefix doap: <http://usefulinc.com/ns/doap#> .\n";
  out << "@prefix units: <http://lv2plug.in/ns/extensions/units#> .\n";
  out << "@prefix ui:   <http://lv2plug.in/ns/extensions/ui#> .\n";
  out << "@prefix pg:   <http://lv2plug.in/ns/ext/port-groups#> .\n";
  out << "@prefix foaf: <http://xmlns.com/foaf/0.1/> .\n";
  out << "@prefix pprops: <http://lv2plug.in/ns/ext/port-props#> .\n";
  out << "@prefix rdf:  <http://www.w3.org/1999/02/22-rdf-syntax-ns#> .\n";
  out << "\n";
  out << "<" << kUri << ">\n";
  out << "    a lv2:Plugin , lv2:DistortionPlugin ;\n";
  out << "    doap:name \"" << kName << "\" ;\n";
  out << "    doap:shortdesc \"" << kShortDesc << "\" ;\n";
  out << "    doap:description \"" << kDescription << "\"@en ;\n";
  out << "    doap:license <" << kLicense << "> ;\n";
  out << "    doap:maintainer [\n";
  out << "        foaf:name \"" << kMaintainer << "\" ;\n";
  out << "        foaf:homepage <" << kHomepage << "> ;\n";
  out << "    ] ;\n";
  out << "    doap:homepage <" << kHomepage << "> ;\n";
  out << "    lv2:majorVersion " << patina::kVersionMajor << " ;\n";
  out << "    lv2:minorVersion " << patina::kVersionMinor << " ;\n";
  out << "    lv2:microVersion " << patina::kVersionMicro << " ;\n";
  out << "    lv2:binary <" << kPluginBinary << "> ;\n";
  out << "    rdfs:seeAlso <manifest.ttl> ;\n";
  out << "    ui:ui <" << kUri << "#ui> ;\n";
  out << "    lv2:optionalFeature lv2:hardRTCapable ;\n";
  out << "    lv2:port\n";

  std::vector<std::string> ports;
  const char* const audio[4][3] = {
      {"in_l", "Input Left", "in"},
      {"in_r", "Input Right", "in"},
      {"out_l", "Output Left", "out"},
      {"out_r", "Output Right", "out"},
  };
  for (int i = 0; i < 4; ++i) {
    std::ostringstream p;
    p << "    [\n";
    p << "        a lv2:AudioPort , lv2:"
      << (std::strcmp(audio[i][2], "in") == 0 ? "InputPort" : "OutputPort")
      << " ;\n";
    p << "        lv2:index " << i << " ;\n";
    p << "        lv2:symbol \"" << audio[i][0] << "\" ;\n";
    p << "        lv2:name \"" << audio[i][1] << "\" ;\n";
    p << "    ]";
    ports.push_back(p.str());
  }

  for (uint32_t id = 0; id < patina::P_COUNT; ++id) {
    const patina::ParamSpec& s = patina::kParamSpecs[id];
    const bool hidden =
        std::strcmp(s.symbol, "band") == 0 || std::strcmp(s.symbol, "meter") == 0;
    ports.push_back(portBlock(
        static_cast<int>(patina::kLv2FirstParam + id), s.symbol, s.name, s.min,
        s.max, s.def, s.stepped, isToggle(s), s.labels, paramUnit(s),
        groupUri(s.module).c_str(), false, hidden));
  }

  for (uint32_t b = 0; b < patina::kLv2BandLevelCount; ++b) {
    const std::string symbol = "band_" + std::to_string(b) + "_level";
    const std::string name = std::string(patina::kBandLabels[b]) + " Level";
    ports.push_back(portBlock(
        static_cast<int>(patina::kLv2FirstBandLevel + b), symbol.c_str(),
        name.c_str(), -120.0, 24.0, -120.0, false, false, {}, "db",
        groupUri("Meter").c_str(), true, false));
  }

  const char* const meterSymbols[] = {"in_peak_l", "in_peak_r", "out_peak_l",
                                      "out_peak_r", "out_vu"};
  const char* const meterNames[] = {"Input Peak Left", "Input Peak Right",
                                    "Output Peak Left", "Output Peak Right",
                                    "Output VU"};
  for (uint32_t i = 0; i < patina::kLv2MeterCount; ++i) {
    ports.push_back(portBlock(
        static_cast<int>(patina::kLv2FirstMeter + i), meterSymbols[i],
        meterNames[i], -120.0, 24.0, -120.0, false, false, {}, "db",
        groupUri("Meter").c_str(), true, false));
  }

  for (uint32_t i = 0; i < patina::kLv2SpectrumCount; ++i) {
    const std::string symbol = "spectrum_" + std::to_string(i);
    const std::string name = "Spectrum " + std::to_string(i);
    ports.push_back(portBlock(
        static_cast<int>(patina::kLv2FirstSpectrum + i), symbol.c_str(),
        name.c_str(), -120.0, 0.0, -120.0, false, false, {}, "db",
        groupUri("Spectrum").c_str(), true, false));
  }

  {
    std::ostringstream p;
    p << "    [\n";
    p << "        a lv2:OutputPort , lv2:ControlPort ;\n";
    p << "        lv2:index " << patina::kLv2Latency << " ;\n";
    p << "        lv2:symbol \"latency\" ;\n";
    p << "        lv2:name \"Latency\" ;\n";
    p << "        lv2:default 0 ;\n";
    p << "        lv2:minimum 0 ;\n";
    p << "        lv2:maximum 100000 ;\n";
    p << "        lv2:designation lv2:latency ;\n";
    p << "        lv2:portProperty pprops:notOnGUI ;\n";
    p << "        pg:group <" << groupUri("Latency") << "> ;\n";
    p << "    ]";
    ports.push_back(p.str());
  }

  for (size_t i = 0; i < ports.size(); ++i) {
    out << ports[i];
    out << (i + 1 == ports.size() ? " .\n" : " ,\n");
  }

  std::vector<std::string> seen;
  std::ostringstream groups;
  auto addGroup = [&](const char* module) {
    const std::string s = groupSlug(module);
    if (std::find(seen.begin(), seen.end(), s) != seen.end()) {
      return;
    }
    seen.push_back(s);
    groups << "\n<" << kUri << "#" << s << "> a pg:Group ; lv2:name \""
           << module << "\" ; lv2:symbol \"" << groupSymbol(module)
           << "\" .\n";
  };
  for (uint32_t id = 0; id < patina::P_COUNT; ++id) {
    addGroup(patina::kParamSpecs[id].module);
  }
  addGroup("Meter");
  addGroup("Spectrum");
  addGroup("Latency");
  out << "\n" << groups.str();
  return out.str();
}

std::string buildManifestTtl() {
  std::ostringstream out;
  out << "# Generated by tools/gen_ttl.cpp - do not edit.\n";
  out << "@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n";
  out << "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n";
  out << "@prefix ui:   <http://lv2plug.in/ns/extensions/ui#> .\n";
  out << "\n";
  out << "<" << kUri << ">\n";
  out << "    a lv2:Plugin , lv2:DistortionPlugin ;\n";
  out << "    lv2:binary <" << kPluginBinary << "> ;\n";
  out << "    rdfs:seeAlso <patina.ttl> , <presets.ttl> ;\n";
  out << "    ui:ui <" << kUri << "#ui> .\n";
  out << "\n";
  out << "<" << kUri << "#ui>\n";
  out << "    a ui:X11UI ;\n";
  out << "    ui:binary <" << kUiBinary << "> ;\n";
  out << "    rdfs:label \"" << kName << " UI\" ;\n";
  out << "    lv2:requiredFeature ui:parent ;\n";
  out << "    lv2:optionalFeature ui:scaleFactor , ui:idleInterface ;\n";
  out << "    lv2:extensionData ui:idleInterface ;\n";
  out << "    rdfs:seeAlso <patina.ttl> .\n";
  return out.str();
}

std::string buildPresetsTtl() {
  struct Bank {
    std::string label;
    std::string uri;
  };
  std::vector<Bank> banks;
  std::vector<std::string> presetBlocks;
  std::set<std::string> used;

  for (int i = 0; i < patina::kPresetCount; ++i) {
    const patina::Preset& p = patina::kPresets[i];
    const std::string bankSlug = slug(p.category == nullptr ? "" : p.category);
    auto it = std::find_if(banks.begin(), banks.end(), [&](const Bank& b) {
      return b.uri == std::string(kUri) + "#bank_" + bankSlug;
    });
    if (it == banks.end()) {
      banks.push_back(
          {p.category == nullptr ? "" : p.category,
           std::string(kUri) + "#bank_" + bankSlug});
    }

    std::string prefix = slug(p.name == nullptr ? "" : p.name);
    std::string presetSlug = prefix;
    int n = 2;
    while (!used.insert(presetSlug).second) {
      presetSlug = prefix + "-" + std::to_string(n++);
    }

    // Emit a complete parameter state.  Presets applied by a host then do
    // not inherit stale band, mode or crossover values from the session.
    double values[patina::P_COUNT];
    for (uint32_t id = 0; id < patina::P_COUNT; ++id) {
      values[id] = patina::kParamSpecs[id].def;
    }
    values[patina::P_MODEL] =
        static_cast<double>(std::min(std::max(p.model, 0), 4));
    for (const patina::PresetValue& v : p.values) {
      if (v.param >= 0 && v.param < static_cast<int>(patina::P_COUNT)) {
        values[v.param] = static_cast<double>(v.value);
      }
    }

    std::ostringstream out;
    out << "<" << kUri << "#preset_" << presetSlug << ">\n";
    out << "    a pset:Preset ;\n";
    out << "    lv2:appliesTo <" << kUri << "> ;\n";
    out << "    rdfs:label \"" << escaped(p.name == nullptr ? "" : p.name)
        << "\" ;\n";
    out << "    rdfs:comment \"" << escaped(p.category == nullptr ? "" : p.category)
        << "\" ;\n";
    out << "    pset:bank <" << kUri << "#bank_" << bankSlug << "> ;\n";
    out << "    lv2:port\n";
    for (uint32_t id = 0; id < patina::P_COUNT; ++id) {
      out << "    [ lv2:symbol \"" << patina::kParamSpecs[id].symbol
          << "\" ; pset:value " << num(values[id]) << " ]"
          << (id + 1 == patina::P_COUNT ? " .\n" : " ,\n");
    }
    presetBlocks.push_back(out.str());
  }

  std::ostringstream out;
  out << "# Generated by tools/gen_ttl.cpp - do not edit.\n";
  out << "@prefix lv2:  <http://lv2plug.in/ns/lv2core#> .\n";
  out << "@prefix pset: <http://lv2plug.in/ns/ext/presets#> .\n";
  out << "@prefix rdfs: <http://www.w3.org/2000/01/rdf-schema#> .\n";
  out << "\n";
  for (const Bank& b : banks) {
    out << "<" << b.uri << ">\n";
    out << "    a pset:Bank ;\n";
    out << "    rdfs:label \"" << escaped(b.label) << "\" .\n";
    out << "\n";
  }
  for (const std::string& block : presetBlocks) {
    out << block << "\n";
  }
  return out.str();
}

bool checkOrWrite(const std::string& path, const std::string& content,
                  bool check) {
  if (check) {
    std::ifstream in(path, std::ios::binary);
    if (!in) {
      std::fprintf(stderr, "gen_ttl: missing %s\n", path.c_str());
      return false;
    }
    std::ostringstream existing;
    existing << in.rdbuf();
    if (existing.str() != content) {
      std::fprintf(stderr,
                   "gen_ttl: %s is out of date - rebuild it with "
                   "`gen_ttl`\n",
                   path.c_str());
      return false;
    }
    return true;
  }
  std::ofstream outFile(path, std::ios::binary | std::ios::trunc);
  if (!outFile) {
    std::fprintf(stderr, "gen_ttl: cannot write %s\n", path.c_str());
    return false;
  }
  outFile << content;
  return true;
}

} // namespace

int main(int argc, char** argv) {
  bool check = false;
  std::string root = ".";
  for (int i = 1; i < argc; ++i) {
    if (std::strcmp(argv[i], "--check") == 0) {
      check = true;
    } else if (std::strcmp(argv[i], "--root") == 0 && i + 1 < argc) {
      root = argv[++i];
    } else if (std::strcmp(argv[i], "--help") == 0) {
      std::printf(
          "usage: gen_ttl [--check] [--root <dir>]\n"
          "  writes <dir>/lv2/{patina,manifest,presets}.ttl\n");
      return 0;
    } else {
      std::fprintf(stderr, "gen_ttl: unknown argument %s\n", argv[i]);
      return 2;
    }
  }

  const std::string dir = root + "/lv2/";
  bool ok = true;
  ok &= checkOrWrite(dir + "patina.ttl", buildPluginTtl(), check);
  ok &= checkOrWrite(dir + "manifest.ttl", buildManifestTtl(), check);
  ok &= checkOrWrite(dir + "presets.ttl", buildPresetsTtl(), check);
  if (!ok) {
    return 1;
  }
  if (!check) {
    std::printf("gen_ttl: wrote %s\n", dir.c_str());
  }
  return 0;
}
