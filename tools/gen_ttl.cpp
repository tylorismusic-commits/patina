// Emits lv2/patina.ttl, lv2/manifest.ttl and lv2/presets.ttl straight from
// src/params.hpp and src/presets.hpp.  The generator is compiled against the
// same headers as the plugin, so metadata cannot drift from the code.
//
//   gen_ttl                 write the files next to ./lv2
//   gen_ttl --check         exit 1 if the committed files are stale
//   gen_ttl --root <dir>    use <dir>/lv2 instead of ./lv2

